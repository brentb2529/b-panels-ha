// Dynamically get an icon component by name
export const getIcon = (name: string, props: any = {}) => {
    switch (name) {
        // Override Icons
        case 'Lightbulb': return <IconLightbulb {...props} />;
        case 'LightbulbOff': return <IconLightbulbOff {...props} />;
        case 'ShieldCheck': return <IconShieldCheck {...props} />;
        case 'ShieldAlert': return <IconShieldAlert {...props} />;
        case 'ShieldOff': return <IconShieldOff {...props} />;
        case 'Zap': return <IconZap {...props} />;
        case 'Power': return <IconPower {...props} />;
        case 'PowerOff': return <IconPowerOff {...props} />;
        case 'CheckCircle': return <IconCheckCircle {...props} />;
        case 'XCircle': return <IconXCircle {...props} />;
        case 'Droplets': return <IconDroplets {...props} />;
        case 'ShadeOpen': return <IconPanelTop {...props} />;
        case 'ShadeClosed': return <IconBlinds {...props} />;
        // Folder Icons
        case 'Square': return <IconSquare {...props} />;
        case 'Sun': return <IconSun {...props} />;
        case 'Shield': return <IconShield {...props} />;
        case 'Camera': return <IconCamera {...props} />;
        case 'Music': return <IconMusic {...props} />;
        case 'Flame': return <IconFlame {...props} />;
        case 'LayoutGrid': return <IconLayoutGrid {...props} />;
        case 'Home': return <IconHome {...props} />;
        case 'Cat': return <IconCat {...props} />;
        default: return null;
    }
};
